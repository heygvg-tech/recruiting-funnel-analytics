"""Render a self-contained HTML funnel report (no external assets)."""
from __future__ import annotations

from html import escape

from .metrics import STAGES, STAGE_LABELS

ACCENT = "#2F6FEB"


def _pct(v: float | None) -> str:
    return "—" if v is None else f"{v:.0%}"


def _days(v: float | None) -> str:
    return "—" if v is None else f"{v:g} days"


def _funnel_svg(counts: dict[str, int]) -> str:
    top = max(counts.values()) or 1
    bar_h, gap, w, label_w = 30, 10, 640, 150
    rows = []
    for i, s in enumerate(STAGES):
        y = i * (bar_h + gap)
        bw = max(2, (w - label_w - 60) * counts[s] / top)
        rows.append(
            f'<text x="0" y="{y + 20}" font-size="13" fill="#333">{STAGE_LABELS[s]}</text>'
            f'<rect x="{label_w}" y="{y}" width="{bw:.1f}" height="{bar_h}" rx="4" fill="{ACCENT}" '
            f'opacity="{1 - i * 0.1:.2f}"/>'
            f'<text x="{label_w + bw + 8:.1f}" y="{y + 20}" font-size="13" fill="#333">{counts[s]}</text>'
        )
    h = len(STAGES) * (bar_h + gap)
    return f'<svg viewBox="0 0 {w} {h}" width="100%" role="img" aria-label="Hiring funnel">{"".join(rows)}</svg>'


def _kpis(s: dict) -> str:
    cards = [
        ("Candidates", str(s["candidates"])),
        ("Hires", str(s["counts"]["hired"])),
        ("Median time to hire", _days(s["time_to_hire"])),
        ("Offer acceptance", _pct(s["offer_acceptance"])),
    ]
    return "".join(f'<div class="kpi"><div class="v">{v}</div><div class="l">{escape(l)}</div></div>'
                   for l, v in cards)


def _stage_table(s: dict) -> str:
    rows = []
    for a, b in zip(STAGES, STAGES[1:]):
        key = f"{a}->{b}"
        flag = ' class="flag"' if key == s["bottleneck"] else ""
        rows.append(f"<tr{flag}><td>{STAGE_LABELS[a]} → {STAGE_LABELS[b]}</td>"
                    f"<td>{_pct(s['pass_through'][key])}</td><td>{_days(s['days_in_stage'][a])}</td></tr>")
    return ("<table><thead><tr><th>Stage</th><th>Pass-through</th><th>Median time in stage</th></tr></thead>"
            f"<tbody>{''.join(rows)}</tbody></table>")


def _source_table(s: dict) -> str:
    rows = "".join(
        f"<tr><td>{escape(r['source'])}</td><td>{r['candidates']}</td><td>{r['screened']}</td>"
        f"<td>{r['hired']}</td><td>{_pct(r['hire_rate'])}</td></tr>" for r in s["sources"])
    return ("<table><thead><tr><th>Source</th><th>Candidates</th><th>Screened</th><th>Hired</th>"
            f"<th>Hire rate</th></tr></thead><tbody>{rows}</tbody></table>")


def _role_table(roles: dict[str, dict]) -> str:
    rows = "".join(
        f"<tr><td>{escape(r)}</td><td>{s['candidates']}</td><td>{s['counts']['hired']}</td>"
        f"<td>{_days(s['time_to_hire'])}</td><td>{_pct(s['offer_acceptance'])}</td></tr>"
        for r, s in roles.items())
    return ("<table><thead><tr><th>Role</th><th>Candidates</th><th>Hires</th><th>Time to hire</th>"
            f"<th>Offer acceptance</th></tr></thead><tbody>{rows}</tbody></table>")


def render(summary: dict, roles: dict[str, dict], title: str = "Recruiting Funnel Report") -> str:
    bn = summary["bottleneck"]
    bn_text = ""
    if bn:
        a, b = bn.split("->")
        bn_text = (f'<p class="note"><strong>Biggest drop-off:</strong> {STAGE_LABELS[a]} → {STAGE_LABELS[b]} '
                   f'({_pct(summary["pass_through"][bn])} pass-through). Start calibration here.</p>')
    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><title>{escape(title)}</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
body{{font-family:-apple-system,Segoe UI,Roboto,sans-serif;max-width:860px;margin:40px auto;padding:0 20px;color:#1a1a1a}}
h1{{font-size:26px;margin-bottom:4px}} h2{{font-size:18px;margin-top:36px}}
.kpis{{display:grid;grid-template-columns:repeat(4,1fr);gap:12px;margin:20px 0}}
.kpi{{border:1px solid #e3e3e3;border-radius:10px;padding:14px}} .v{{font-size:24px;font-weight:700;color:{ACCENT}}}
.l{{font-size:12px;color:#666;margin-top:4px}}
table{{width:100%;border-collapse:collapse;font-size:14px}} th,td{{text-align:left;padding:8px;border-bottom:1px solid #eee}}
th{{color:#666;font-weight:600}} tr.flag td{{background:#FFF4E5}} .note{{background:#F3F6FD;padding:12px;border-radius:8px}}
</style></head><body>
<h1>{escape(title)}</h1><div style="color:#666">Generated by recruiting-funnel-analytics</div>
<div class="kpis">{_kpis(summary)}</div>
{bn_text}
<h2>Funnel</h2>{_funnel_svg(summary["counts"])}
<h2>Stage conversion</h2>{_stage_table(summary)}
<h2>Source of hire</h2>{_source_table(summary)}
<h2>By role</h2>{_role_table(roles)}
</body></html>"""
